"""Real-price replay: rerun the main (q=1) sweep with a provider-calibrated
$-per-M-output-token cost vector instead of the parameter-count proxy.

Price rule (documented in the paper): exact OpenRouter output price where the
model is listed (accessed July 2026); otherwise the median output price of
same-size-tier text models on the same catalog (7-9B: $0.15/M, n=13;
14-16B: $0.24/M, n=5; 30-34B: $0.458/M, n=12).

Outputs: results/pareto_<bench>_realcost.csv + ../paper/tab_realcost.tex
Usage:   python run_real_costs.py
"""
import csv
import os

import numpy as np

import data as data_mod
from data import load_bench
from policies import POLICIES

HERE = os.path.dirname(os.path.abspath(__file__))
PAPER = os.path.join(HERE, "..", "paper_canonical")
RES = os.path.join(HERE, "results")

# model order in the tensors (meta["models"]):
#  0 mistralai/Mistral-7B-Instruct-v0.3      -> tier 7-9B median      0.15
#  1 deepseek-ai/DeepSeek-R1-Distill-Qwen-7B -> tier 7-9B median      0.15
#  2 Qwen/Qwen2.5-7B-Instruct-AWQ            -> exact OpenRouter      0.10
#  3 Qwen/Qwen2.5-14B-Instruct-AWQ           -> tier 14-16B median    0.24
#  4 Qwen/Qwen2.5-32B-Instruct-AWQ           -> tier 30-34B median    0.458
#  5 microsoft/phi-4                         -> exact OpenRouter      0.14
#  6 allenai/OLMo-2-1124-7B-Instruct         -> tier 7-9B median      0.15
#  7 01-ai/Yi-1.5-9B-Chat                    -> tier 7-9B median      0.15
#  8 ibm-granite/granite-3.3-8b-instruct     -> tier 7-9B median      0.15
#  9 google/gemma-2-9b-it                    -> tier 7-9B median      0.15
# 10 meta-llama/Llama-3.1-8B-Instruct        -> exact OpenRouter      0.03
REAL_PRICES = np.array([0.15, 0.15, 0.10, 0.24, 0.458, 0.14,
                        0.15, 0.15, 0.15, 0.15, 0.03])

BENCHES = ["gsm8k", "math500", "gpqa", "humanevalplus"]
TRIALS = 20
SEED = 0


def compute_priors(b_train):
    succ = b_train.sum(axis=(0, 2)).astype(float)
    total = b_train.shape[0] * b_train.shape[2]
    return succ + 1.0, (total - succ) + 1.0, int(np.argmax(b_train.mean(axis=(0, 2))))


def main():
    for bench in BENCHES:
        d = load_bench(bench)
        d["costs"] = REAL_PRICES.copy()
        b, costs, N, qr = d["b"], d["costs"], d["N"], d["q_router"]
        rng = np.random.default_rng(SEED)
        idx = rng.permutation(N)
        tr, te = idx[: N // 2], idx[N // 2:]
        a0, b0, best = compute_priors(b[tr])
        budgets = np.unique(np.round(
            np.linspace(costs.min(), 6 * costs.max(), 12), 3)).astype(float)
        rows = []
        for name, policy in POLICIES.items():
            for B in budgets:
                accs, cs = [], []
                for t in range(TRIALS):
                    trng = np.random.default_rng(SEED * 100003 + t)
                    for i in te:
                        ctx = {"a0": a0, "b0": b0, "best_acc_model": best,
                               "q_router_i": float(qr[i]), "stop_on_correct": True}
                        drawn, cost = policy(b[i], costs, float(B), ctx, trng)
                        accs.append(1.0 if any(c == 1 for c in drawn) else 0.0)
                        cs.append(cost)
                rows.append({"policy": name, "budget": float(B),
                             "mean_cost": float(np.mean(cs)),
                             "accuracy": float(np.mean(accs))})
                if name in ("single_route", "learned_router"):
                    break
        out = os.path.join(RES, f"pareto_{bench}_realcost.csv")
        with open(out, "w", newline="") as f:
            w = csv.DictWriter(f, fieldnames=["policy", "budget", "mean_cost", "accuracy"])
            w.writeheader(); w.writerows(rows)
        print("wrote", out)

    # matched-cost table at the point nearest mean_cost = 0.6 (a mid budget in $)
    TARGET = 0.6

    def near(bench, pol):
        rows = list(csv.DictReader(open(os.path.join(RES, f"pareto_{bench}_realcost.csv"))))
        pts = sorted((float(r["mean_cost"]), float(r["accuracy"]))
                     for r in rows if r["policy"] == pol)
        return min(pts, key=lambda p: abs(p[0] - TARGET)) if pts else (None, None)

    order = [("resample_or_reroute", "RoR (ours)"),
             ("fixed_best_of_k", "budget-aware best-of-$K$"),
             ("frugal_cascade", "cascade"),
             ("random_alloc", "random allocation"),
             ("learned_router", "router (one commit)"),
             ("single_route", "single-route (best model)")]
    lines = [
        "% AUTO-GENERATED by experiments/run_real_costs.py -- do not hand-edit.",
        "\\begin{table*}[t]\\centering\\footnotesize",
        "\\caption{Real-price replay (provider-calibrated \\$ per M output tokens;"
        " exact OpenRouter prices for three listed models, size-tier medians"
        " otherwise, accessed July 2026): accuracy at the point nearest mean cost"
        " \\$0.6 per 1k queries scale. Cost ordering differs from the parameter"
        " proxy (e.g.\\ Phi-4 is cheaper than most 7--9B models; Llama-3.1-8B is"
        " $5\\times$ cheaper than same-size peers).}",
        "\\label{tab:realcost}",
                "\\begin{tabular}{lcccccccc}\\toprule",
        " & \\multicolumn{2}{c}{GSM8K} & \\multicolumn{2}{c}{MATH-500} & \\multicolumn{2}{c}{GPQA} & \\multicolumn{2}{c}{HumanEval+} \\\\",
        "Policy & cost & acc & cost & acc & cost & acc & cost & acc \\\\ \\midrule",
    ]
    for pol, disp in order:
        row = [f"\\textbf{{{disp}}}" if pol == "resample_or_reroute" else disp]
        for bench in BENCHES:
            c, a = near(bench, pol)
            cc = f"{c:.2f}" if c is not None else "--"
            aa = f"{a:.3f}" if a is not None else "--"
            if pol == "resample_or_reroute":
                cc, aa = f"\\textbf{{{cc}}}", f"\\textbf{{{aa}}}"
            row += [cc, aa]
        lines.append(" & ".join(row) + " \\\\")
    lines += ["\\bottomrule\\end{tabular}\\end{table*}"]
    open(os.path.join(PAPER, "tab_realcost.tex"), "w").write("\n".join(lines) + "\n")
    print("wrote tab_realcost.tex")


if __name__ == "__main__":
    main()
