"""Latency proxy: expected number of SEQUENTIAL rounds (round-trips) per query.

Cost (in $ or param-proxy) is not the only deployment axis: a policy that draws
one sample at a time, inspecting each before deciding the next, incurs a
round-trip PER draw. This is the latency price of adaptivity.

  * resample_or_reroute, frugal_cascade : inherently SEQUENTIAL — each draw's
    outcome informs the next choice, so #rounds = #draws.
  * fixed_best_of_k                     : the K draws of the chosen model can be
    issued in ONE parallel batch → 1 round (we still report #draws for context).
  * single_route, learned_router        : 1 draw → 1 round.

We report, per policy at a matched budget, the mean #draws (= sequential rounds
for the adaptive policies) alongside the accuracy it buys — the accuracy x cost x
latency trade-off. Emits results/latency_<bench>.csv + ../paper_canonical/tab_latency.tex.
"""
import argparse
import csv
import os

import numpy as np

from data import load_bench
from policies import POLICIES
from run_pareto import compute_priors

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "results")
PAPER = os.path.join(HERE, "..", "paper_canonical")
BENCHES = ["gsm8k", "math500", "gpqa", "humanevalplus"]

# whether a policy's draws can be issued in parallel (1 round) or must be sequential
PARALLELIZABLE = {"single_route": True, "learned_router": True, "fixed_best_of_k": True,
                  "resample_or_reroute": False, "resample_or_reroute_ucb": False,
                  "frugal_cascade": False, "random_alloc": False}
REPORT = ["single_route", "fixed_best_of_k", "frugal_cascade", "resample_or_reroute"]


def rounds_for(bench, budget_mult=6.0, trials=20, seed=0):
    d = load_bench(bench)
    b, costs, N, qr = d["b"], d["costs"], d["N"], d["q_router"]
    rng = np.random.default_rng(seed)
    idx = rng.permutation(N)
    tr, te = idx[: N // 2], idx[N // 2:]
    a0, b0, best = compute_priors(b[tr])
    B = float(np.round(costs.min() + budget_mult * (costs.max() - costs.min())))
    out = {}
    for name in REPORT:
        policy = POLICIES[name]
        draws, accs = [], []
        for t in range(trials):
            trng = np.random.default_rng(seed * 100003 + t)
            for i in te:
                ctx = {"a0": a0, "b0": b0, "best_acc_model": best,
                       "q_router_i": float(qr[i]), "stop_on_correct": True}
                drawn, _ = policy(b[i], costs, B, ctx, trng)
                draws.append(len(drawn))
                accs.append(1.0 if any(c == 1 for c in drawn) else 0.0)
        seq = 1.0 if PARALLELIZABLE[name] else float(np.mean(draws))
        out[name] = {"mean_draws": float(np.mean(draws)),
                     "seq_rounds": seq, "acc": float(np.mean(accs)),
                     "parallel": PARALLELIZABLE[name]}
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--bench", default="humanevalplus")
    ap.add_argument("--trials", type=int, default=20)
    args = ap.parse_args()
    os.makedirs(RES, exist_ok=True)

    allres = {}
    for bench in BENCHES:
        r = rounds_for(bench, trials=args.trials)
        allres[bench] = r
        with open(os.path.join(RES, f"latency_{bench}.csv"), "w", newline="") as f:
            w = csv.DictWriter(f, fieldnames=["policy", "mean_draws", "seq_rounds", "acc", "parallel"])
            w.writeheader()
            for name, v in r.items():
                w.writerow({"policy": name, **v})
        print(f"[{bench}]")
        for name in REPORT:
            v = r[name]
            tag = "parallel(1 round)" if v["parallel"] else "SEQUENTIAL"
            print(f"  {name:22s} draws={v['mean_draws']:5.2f} rounds={v['seq_rounds']:5.2f} "
                  f"acc={v['acc']:.3f}  [{tag}]")

    # LaTeX table: sequential rounds per policy per benchmark
    labels = {"single_route": "single-route", "fixed_best_of_k": "best-of-$K$ (parallel)",
              "frugal_cascade": "cascade", "resample_or_reroute": "RoR (ours)"}
    titles = {"gsm8k": "GSM8K", "math500": "MATH-500", "gpqa": "GPQA", "humanevalplus": "HumanEval+"}
    lines = ["% auto-generated by run_latency.py — mean sequential rounds (round-trips) per query",
             "\\begin{table}[t]\\centering",
             "\\caption{Latency proxy: mean sequential rounds (round-trips) per query at matched budget. "
             "RoR and cascade are adaptive (one draw per round); best-of-$K$ and single-route issue their draws in a single parallel round.}",
             "\\label{tab:latency}",
             "\\resizebox{\\columnwidth}{!}{%",
             "\\begin{tabular}{l" + "c" * len(BENCHES) + "}\\toprule",
             " & " + " & ".join(titles[b] for b in BENCHES) + " \\\\ \\midrule"]
    for name in REPORT:
        cells = [f"{allres[b][name]['seq_rounds']:.1f}" for b in BENCHES]
        lines.append(f"{labels[name]} & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule\\end{tabular}}\\end{table}"]
    open(os.path.join(PAPER, "tab_latency.tex"), "w").write("\n".join(lines) + "\n")
    print("wrote tab_latency.tex")


if __name__ == "__main__":
    main()
